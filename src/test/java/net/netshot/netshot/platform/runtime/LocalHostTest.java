package net.netshot.netshot.platform.runtime;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledOnOs;
import org.junit.jupiter.api.condition.OS;

import net.netshot.netshot.testing.UnitTest;

@UnitTest
@DisplayName("Local machine")
class LocalHostTest {

	@Test
	@EnabledOnOs(OS.LINUX)
	@DisplayName("The hostname is the one of the kernel, without running a command")
	void hostname() throws Exception {
		String expected = Files.readString(Path.of("/proc/sys/kernel/hostname"), StandardCharsets.UTF_8).strip();
		Assertions.assertEquals(expected, LocalHost.name());
	}
}
