package net.netshot.netshot.api.rest.v1;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Marks a component of a v1 representation which is part of its brief view (beside {@code id}, {@code url}
 * and {@code display}, always there). The brief view is the default one of the lists, and the form of an object
 * referenced by another one (see {@link Ref}).
 */
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.RECORD_COMPONENT)
public @interface Brief {
}
